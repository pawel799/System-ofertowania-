export const RAL_CLASSIC: RalColor[] = DATA.map(([code, name, hex, group]) => ({ code, name, hex, group }));

const BY_CODE = new Map(RAL_CLASSIC.map((c) => [c.code, c]));

/** Kolor po kodzie ("9010" albo "RAL 9010"); undefined, gdy takiego nie ma w RAL Classic. */
export function ralByCode(code: string): RalColor | undefined {
  return BY_CODE.get(code.replace(/^RAL\s*/i, "").trim());
}
